"""Numbers added for the internal review (2026-10-30). Writes numbers_review.tex and
replaces the seed-0 probe and slice-position outputs by means over all available seeds.

  * HD95 exclusions: volume-structure pairs where a structure was missing from the
    prediction or the reference (HD95 undefined), on ACDC and the external datasets;
  * linear probes: mean over seeds of every probe macro, the probe table and the
    depth curves (seed 0 from --paper_results, seeds 1-4 from work/probe_seeds/s<k>);
  * slice position: mean over seeds of basal / mid / apical Dice;
  * parameter count of the affine instance norms added to Swin-UNETR.
Run after stats_revision.py and make_tables.py --all_seeds.
"""
import argparse
import glob
import json
import re
import shutil
from pathlib import Path

import numpy as np
import pandas as pd

TYPES = ["motion", "noise", "blur", "bias", "undersample"]
SEEDS = ["", "_s1", "_s2", "_s3", "_s4"]


def hd_exclusions(work, macros):
    n = m = 0
    for f in glob.glob(str(work / "runs" / "*" / "eval_seg.csv")):
        d = pd.read_csv(f, usecols=["hd95"])
        n, m = n + len(d), m + int(d.hd95.isna().sum())
    ext = []
    for ds in ("cmrx_eval", "mnms_eval"):
        a = b = 0
        for f in glob.glob(str(work / ds / "*.csv")):
            if f.endswith(("_clin.csv", "estimator.csv")):
                continue
            d = pd.read_csv(f)
            if "hd95" in d:
                a, b = a + len(d), b + int(d.hd95.isna().sum())
        ext.append(100 * b / max(a, 1))
    macros += [f"\\newcommand{{\\HDExclACDC}}{{{m}}}",
               f"\\newcommand{{\\HDExclACDCTotal}}{{{n:,}}}".replace(",", "{,}"),
               f"\\newcommand{{\\HDExclExtPct}}{{{max(ext):.2f}}}"]


def probes(work, res, macros):
    """Average probe macros, table cells and depth curves over seeds."""
    dirs = [res] + [work / "probe_seeds" / f"s{k}" for k in range(1, 5)]
    dirs = [d for d in dirs if (d / "numbers_probe.tex").exists()]
    if len(dirs) < 2:
        return
    seed0 = work / "probe_seed0"
    seed0.mkdir(exist_ok=True)
    for f in ("numbers_probe.tex", "table_probe.tex", "probe_depth_unet.csv", "probe_depth_swinunetr.csv"):
        if (res / f).exists() and not (seed0 / f).exists():
            shutil.copy(res / f, seed0 / f)  # keep the seed-0 version once
    src = [seed0 if d == res else d for d in dirs]
    pat = re.compile(r"\\newcommand\{\\(\w+)\}\{([-\d.]+)\}")
    vals = {}
    for d in src:
        for k, v in pat.findall((d / "numbers_probe.tex").read_text()):
            vals.setdefault(k, []).append(float(v))
    out = [f"% generated by stats_review.py: probe values averaged over {len(src)} seeds"]
    for k, v in vals.items():
        out.append(f"\\newcommand{{\\{k}}}{{{np.mean(v):.{3 if k.endswith('MAE') else 2}f}}}")
    (res / "numbers_probe.tex").write_text("\n".join(out) + "\n")
    macros.append(f"\\newcommand{{\\ProbeNSeeds}}{{{len(src)}}}")
    # table: average every numeric cell row by row (all seed tables have the same layout)
    tabs = [(d / "table_probe.tex").read_text().splitlines() for d in src]
    num = re.compile(r"-?\d+\.\d+")
    lines = []
    for rows in zip(*tabs):
        if num.search(rows[0]) and "&" in rows[0]:
            cells = [list(map(float, num.findall(r))) for r in rows]
            mean = np.mean(cells, axis=0)
            it = iter(mean)
            dec = [len(x.split(".")[1]) for x in num.findall(rows[0])]
            di = iter(dec)
            lines.append(num.sub(lambda _: f"{next(it):.{next(di)}f}", rows[0]))
        else:
            lines.append(rows[0])
    (res / "table_probe.tex").write_text("\n".join(lines))
    for b in ("unet", "swinunetr"):
        fs = [d / f"probe_depth_{b}.csv" for d in src if (d / f"probe_depth_{b}.csv").exists()]
        if fs:
            dfs = [pd.read_csv(f) for f in fs]
            m = dfs[0].copy()
            cols = [c for c in m.columns if c.startswith(("auc_", "mae_"))]
            m[cols] = np.nanmean([d[cols].to_numpy(float) for d in dfs], axis=0)
            m.to_csv(res / f"probe_depth_{b}.csv", index=False, float_format="%.4f", na_rep="nan")


def slices(runs, res, macros):
    """Basal / mid / apical Dice, mean over the seeds that have slices.csv."""
    vers = [("default", "Default"), ("aug", "Augmentation-only"), ("dacm", "DACM (stage)"), ("dacmnorm", "DACM (norm)")]
    backs = [("unet", "U-Net"), ("swinunetr", "Swin-UNETR")]
    lines = [r"\begin{tabular}{@{}llcccccc@{}}", r"\toprule",
             r" & & \multicolumn{3}{c}{Clean} & \multicolumn{3}{c}{$s{=}1.0$} \\",
             r"\cmidrule(lr){3-5}\cmidrule(l){6-8}",
             r"Backbone & Version & Basal & Mid & Apical & Basal & Mid & Apical \\", r"\midrule"]
    out = ["% generated by stats_review.py: slice position, mean over seeds"]
    nmin = 5
    for bi, (b, bl) in enumerate(backs):
        for j, (v, vl) in enumerate(vers):
            fs = [runs / f"{b}_{v}{s}" / "slices.csv" for s in SEEDS if (runs / f"{b}_{v}{s}" / "slices.csv").exists()]
            if not fs:
                continue
            nmin = min(nmin, len(fs))
            cells = []
            for clean in (True, False):
                for p in ("Basal", "Mid", "Apical"):
                    per = []
                    for f in fs:
                        d = pd.read_csv(f)
                        d = d[(d.cond == "clean_0.0") == clean]
                        per.append(d.groupby(["cond", "pid", "pos"]).dice.mean().reset_index()
                                   .query("pos == @p").dice.mean())
                    val = f"{100 * np.mean(per):.1f}"
                    cells.append(val)
                    out.append(f"\\newcommand{{\\Slice{b.replace('swinunetr', 'swin')}{v}{'Clean' if clean else 'Ten'}{p}}}{{{val}}}")
            lines.append(f"{bl if j == 0 else ''} & {vl} & " + " & ".join(cells) + r" \\")
        if bi == 0:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (res / "table_slices.tex").write_text("\n".join(lines))
    (res / "numbers_slices.tex").write_text("\n".join(out) + "\n")
    macros.append(f"\\newcommand{{\\SliceNSeeds}}{{{nmin}}}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", required=True)
    ap.add_argument("--paper_results", required=True)
    a = ap.parse_args()
    work, res = Path(a.work), Path(a.paper_results)
    macros = ["% generated by stats_review.py"]
    hd_exclusions(work, macros)
    probes(work, res, macros)
    slices(work / "runs", res, macros)
    pa = work / "runs" / "swinunetr_augaff" / "params.json"
    pb = work / "runs" / "swinunetr_aug" / "params.json"
    if pa.exists() and pb.exists():
        n = json.loads(pa.read_text())["params_total"] - json.loads(pb.read_text())["params_total"]
        macros.append(f"\\newcommand{{\\SwinAffParams}}{{{n:,}}}".replace(",", "{,}"))
    (res / "numbers_review.tex").write_text("\n".join(macros) + "\n")
    print("\n".join(macros))


if __name__ == "__main__":
    main()
