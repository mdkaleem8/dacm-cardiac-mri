"""Seed-to-seed summary for a group of runs (seeds 0, 1, 2).

Run folders are named <backbone>_<version><tag><seed>, with seed "" (seed 0),
"_s1" or "_s2"; tag is "" for the main experiment, "_low" for the reduced
training set and "_cap" for capped training severity.
For each version: mean Dice per seed (clean, s=0.6, s=1.0; averaged over the
five types), then mean and SD over seeds. Paired comparisons use per-subject
Dice averaged over seeds (Wilcoxon signed-rank), Holm-corrected within each
severity level. Writes table_seeds_<b><tag>.tex and numbers_seeds_<b><tag>.tex.
"""
import argparse
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

TYPES = ["motion", "noise", "blur", "bias", "undersample"]
LABEL = {"aug": "Augmentation-only", "dacmnorm": "DACM (norm)", "dacmzero": r"Module, $\mathbf{z}{=}0$",
         "dacmshuf": r"Module, $\mathbf{z}$ shuffled"}
SHORT = {"aug": "Aug", "dacmnorm": "Norm", "dacmzero": "Zero", "dacmshuf": "Shuf"}
LEVELS = [(0, "Clean"), (0.6, "Six"), (1.0, "Ten")]
SEEDS = ["", "_s1", "_s2"]
TAGMACRO = {"": "", "_low": "Low", "_cap": "Cap"}


def per_subject(csv, level):
    d = pd.read_csv(csv)
    d = d[d.variant == "est"]
    d = d[d.type == "clean"] if level == 0 else d[d.type.isin(TYPES) & (d.level == level)]
    return d.groupby("pid").dice.mean()


def holm(ps):
    order = np.argsort(ps)
    adj, m, run = np.empty(len(ps)), len(ps), 0.0
    for i, k in enumerate(order):
        run = max(run, min(1.0, (m - i) * ps[k]))
        adj[k] = run
    return adj


def pfmt(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs_root", required=True)
    ap.add_argument("--paper_results", required=True)
    ap.add_argument("--backbone", default="unet")
    ap.add_argument("--tag", default="", choices=list(TAGMACRO))
    ap.add_argument("--versions", nargs="+", default=["aug", "dacmnorm", "dacmzero"])
    a = ap.parse_args()
    root, out, b, tag = Path(a.runs_root), Path(a.paper_results), a.backbone, a.tag
    subj = {}
    for v in a.versions:
        for lv, _ in LEVELS:
            cols = {}
            for s in SEEDS:
                f = root / f"{b}_{v}{tag}{s}" / "eval_seg.csv"
                if f.exists():
                    cols[s or "_s0"] = per_subject(f, lv)
            subj[(v, lv)] = pd.DataFrame(cols)
    n_seeds = min(df.shape[1] for df in subj.values())
    if n_seeds < 2:
        raise SystemExit(f"need at least two seeds per version for tag '{tag}'")
    # use the same seeds for every version
    common = sorted(set.intersection(*[set(df.columns) for df in subj.values()]))
    subj = {k: df[common] for k, df in subj.items()}

    key = b.replace("swinunetr", "swin") + TAGMACRO[tag]
    macros = [f"% generated by seed_summary.py (tag '{tag}')", f"\\newcommand{{\\Seed{key}N}}{{{len(common)}}}"]
    lines = [r"\begin{tabular}{@{}lccc@{}}", r"\toprule",
             r"Version & Clean & $s{=}0.6$ & $s{=}1.0$ \\", r"\midrule"]
    for v in a.versions:
        cells = []
        for lv, lt in LEVELS:
            per_seed = 100 * subj[(v, lv)].mean(axis=0).to_numpy()
            m, sd = per_seed.mean(), per_seed.std(ddof=1)
            cells.append(f"{m:.1f} $\\pm$ {sd:.2f}")
            # 'Ten' keeps the older macro names used in the paper
            tg = {"Clean": "Clean", "Six": "Six", "Ten": "Ten"}[lt]
            macros += [f"\\newcommand{{\\Seed{key}{v}{tg}}}{{{m:.1f}}}",
                       f"\\newcommand{{\\Seed{key}{v}{tg}SD}}{{{sd:.2f}}}"]
        lines.append(f"{LABEL[v]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    pairs = [(v1, v2) for v1, v2 in combinations(a.versions, 2)]
    pairs = [(v2, v1) if v2 != "aug" and v1 == "aug" else (v1, v2) for v1, v2 in pairs]  # X vs Aug
    for lv, lt in LEVELS:
        raw, rows = [], []
        for v1, v2 in pairs:
            x1, x2 = subj[(v1, lv)].mean(axis=1).align(subj[(v2, lv)].mean(axis=1), join="inner")
            per_seed = 100 * (subj[(v1, lv)].mean(axis=0).to_numpy() - subj[(v2, lv)].mean(axis=0).to_numpy())
            raw.append(wilcoxon(x1, x2).pvalue)
            rows.append((f"{SHORT[v1]}Vs{SHORT[v2]}", 100 * float((x1 - x2).mean()), per_seed))
        for (name, d, per_seed), p, pa in zip(rows, raw, holm(np.array(raw))):
            suf = "" if lt == "Ten" else lt  # s=1.0 macros keep their original names
            macros += [f"\\newcommand{{\\Seed{key}{name}{suf}Delta}}{{{d:.2f}}}",
                       f"\\newcommand{{\\Seed{key}{name}{suf}P}}{{{pfmt(p)}}}",
                       f"\\newcommand{{\\Seed{key}{name}{suf}Holm}}{{{pfmt(pa)}}}",
                       f"\\newcommand{{\\Seed{key}{name}{suf}Wins}}{{{int((per_seed > 0).sum())}}}"]
    out.mkdir(parents=True, exist_ok=True)
    (out / f"table_seeds_{b}{tag}.tex").write_text("\n".join(lines))
    (out / f"numbers_seeds_{b}{tag}.tex").write_text("\n".join(macros) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
