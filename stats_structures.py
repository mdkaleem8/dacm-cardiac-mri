"""Per-structure clean Dice next to published ACDC values, and an analysis of failure cases.

Writes into --paper_results:
  table_structures.tex   clean Dice per phase and structure (ours, official nnU-Net, published values)
  fail_points_<b>.csv    one point per test subject and type at severity 1.0 (for the strip plot)
  numbers_structures.tex macros \\Struct..., \\Fail...
Published values are transcribed from Bernard et al., IEEE TMI 2018, Tables III and VII
(see literature_review/refs/bernard2018_observer_values.md).
"""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

TYPES = ["motion", "noise", "blur", "bias", "undersample"]
SEEDS = ["", "_s1", "_s2", "_s3", "_s4"]
CELLS = [("ED", "LV"), ("ED", "RV"), ("ED", "Myo"), ("ES", "LV"), ("ES", "RV"), ("ES", "Myo")]
# Bernard et al. 2018: Table III (best challenge method, Isensee et al.) and Table VII (O1a vs O2), Dice x 100
PUBLISHED = [("Best ACDC challenge entry~\\citep{bernard2018acdc}", [96.8, 94.6, 90.2, 93.1, 89.9, 91.9]),
             ("Inter-observer~\\citep{bernard2018acdc}", [95.6, 93.0, 87.0, 89.8, 86.6, 89.1])]
MODELS = [("unet_aug", "U-Net, augmentation-only"), ("unet_dacmnorm", "U-Net, \\method{} (norm)"),
          ("nnunet_default", "Official nnU-Net, default augm."),
          ("swinunetr_aug", "Swin-UNETR, augmentation-only"), ("swinunetr_dacmnorm", "Swin-UNETR, \\method{} (norm)")]
FAIL_T = 0.85  # a subject-type case "fails" when its mean foreground Dice at s=1.0 is below this


def load(root, name):
    fs = [(i, root / f"{name}{s}" / "eval_seg.csv") for i, s in enumerate(SEEDS)]
    d = pd.concat([pd.read_csv(f).assign(seed=i) for i, f in fs if f.exists()])
    return d[d.variant == "est"]


def key(name):
    return name.replace("swinunetr", "swin").replace("_", "")


def type_matrix(root, name, typ, level=1.0):
    """Subjects x seeds matrix of mean foreground Dice for one degradation type at one level."""
    cols = {}
    for s in SEEDS:
        f = root / f"{name}{s}" / "eval_seg.csv"
        if f.exists():
            d = pd.read_csv(f)
            d = d[(d.variant == "est") & (d.type == typ) & (d.level == level)]
            cols[s or "_s0"] = d.groupby("pid").dice.mean()
    return pd.DataFrame(cols)


def pertype(root, out, macros):
    """Primary comparison split by degradation type (severity 1.0, five seeds): DACM (norm) minus
    augmentation-only and minus the zero-conditioned module, with two-level bootstrap 95% CIs."""
    from stats_revision import boot_diff  # same bootstrap as the main analysis
    names = {"motion": "Motion", "noise": "Noise", "blur": "Blur", "bias": "Bias field", "undersample": "Undersampling"}
    lines = [r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
             r" & \multicolumn{2}{c}{U-Net (nnU-Net configuration)} & \multicolumn{2}{c}{Swin-UNETR} \\",
             r"\cmidrule(lr){2-3}\cmidrule(l){4-5}",
             r"Type & vs aug.-only & vs $\mathbf{z}{=}0$ & vs aug.-only & vs $\mathbf{z}{=}0$ \\", r"\midrule"]
    for t_ in TYPES:
        cells = []
        for b in ("unet", "swinunetr"):
            k = key(b)
            m1 = 100 * type_matrix(root, f"{b}_dacmnorm", t_)
            for ref, tag in (("aug", "Aug"), ("dacmzero", "Zero")):
                a1, a2 = m1.align(100 * type_matrix(root, f"{b}_{ref}", t_), join="inner", axis=0)
                bs = boot_diff(a1.to_numpy(), a2.to_numpy(), 4000)
                d = a1.to_numpy().mean() - a2.to_numpy().mean()
                lo, hi = np.percentile(bs, [2.5, 97.5])
                cells.append(f"${d:+.2f}$ [${lo:+.2f}$, ${hi:+.2f}$]")
                tk = t_.capitalize()
                macros += [f"\\newcommand{{\\PT{k}{tk}NormVs{tag}Delta}}{{{d:.2f}}}",
                           f"\\newcommand{{\\PT{k}{tk}NormVs{tag}Lo}}{{{lo:.2f}}}",
                           f"\\newcommand{{\\PT{k}{tk}NormVs{tag}Hi}}{{{hi:.2f}}}"]
            if b == "unet":
                macros.append(f"\\newcommand{{\\PT{k}{t_.capitalize()}Aug}}"
                              f"{{{100 * type_matrix(root, 'unet_aug', t_).to_numpy().mean():.1f}}}")
        lines.append(f"{names[t_]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (out / "table_pertype_seeds.tex").write_text("\n".join(lines))
    print("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs_root", required=True)
    ap.add_argument("--cache", required=True)
    ap.add_argument("--paper_results", required=True)
    a = ap.parse_args()
    root, out = Path(a.runs_root), Path(a.paper_results)
    meta = json.loads((Path(a.cache) / "meta.json").read_text())
    macros = ["% generated by stats_structures.py", f"\\newcommand{{\\FailThr}}{{{int(100 * FAIL_T)}}}"]

    # ---- clean Dice per phase and structure
    lines = [r"\begin{tabular}{@{}lccccccc@{}}", r"\toprule",
             r" & & \multicolumn{3}{c}{ED} & \multicolumn{3}{c}{ES} \\",
             r"\cmidrule(lr){3-5}\cmidrule(l){6-8}",
             r"Model & Seeds & LV & RV & Myo & LV & RV & Myo \\", r"\midrule"]
    for name, label in MODELS:
        d = load(root, name)
        c = d[d.type == "clean"]
        # mean over subjects within a seed, then over seeds
        m = 100 * c.groupby(["seed", "phase", "cls"]).dice.mean().groupby(["phase", "cls"]).mean()
        vals = [m[(p, s)] for p, s in CELLS]
        lines.append(f"{label} & {c.seed.nunique()} & " + " & ".join(f"{v:.1f}" for v in vals) + r" \\")
        macros += [f"\\newcommand{{\\Struct{key(name)}{p}{s}}}{{{v:.1f}}}" for (p, s), v in zip(CELLS, vals)]
        if name == "nnunet_default":
            lines.append(r"\midrule")
    lines.append(r"\midrule")
    for label, vals in PUBLISHED:
        lines.append(f"{label} & -- & " + " & ".join(f"{v:.1f}" for v in vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (out / "table_structures.tex").write_text("\n".join(lines))

    # ---- failure cases at s = 1.0
    for name in ("unet_aug", "unet_dacmnorm", "nnunet_default", "swinunetr_aug", "swinunetr_dacmnorm"):
        k = key(name)
        d = load(root, name)
        t = d[d.type.isin(TYPES) & (d.level == 1.0)]
        st = t.groupby(["pid", "type"]).dice.mean().reset_index()  # mean over phases, structures, seeds
        st["group"] = st.pid.map(lambda p: meta[p]["group"])
        fail = st[st.dice < FAIL_T]
        macros += [f"\\newcommand{{\\Fail{k}N}}{{{len(fail)}}}", f"\\newcommand{{\\Fail{k}Total}}{{{len(st)}}}",
                   f"\\newcommand{{\\Fail{k}Motion}}{{{(fail.type == 'motion').sum()}}}",
                   f"\\newcommand{{\\Fail{k}HCM}}{{{(fail.group == 'HCM').sum()}}}",
                   f"\\newcommand{{\\Fail{k}Subjects}}{{{fail.pid.nunique()}}}"]
        # structures in the worst tenth of cases versus all cases
        worst = st[st.dice <= st.dice.quantile(0.1)][["pid", "type"]]
        tw = t.merge(worst, on=["pid", "type"])
        for (p, s) in CELLS:
            macros += [f"\\newcommand{{\\Fail{k}Worst{p}{s}}}{{{100 * tw[(tw.phase == p) & (tw.cls == s)].dice.mean():.1f}}}",
                       f"\\newcommand{{\\Fail{k}All{p}{s}}}{{{100 * t[(t.phase == p) & (t.cls == s)].dice.mean():.1f}}}"]
        # the three subjects with the lowest mean Dice at s=1.0, and their clean Dice and rank
        subj = st.groupby("pid").dice.mean().sort_values()
        clean = d[d.type == "clean"].groupby("pid").dice.mean().sort_values()
        for i, (p, v) in enumerate(subj.head(3).items(), 1):
            r = ["One", "Two", "Three"][i - 1]
            macros += [f"\\newcommand{{\\Fail{k}Subj{r}}}{{{p.replace('patient', '')}}}",
                       f"\\newcommand{{\\Fail{k}Subj{r}Group}}{{{meta[p]['group']}}}",
                       f"\\newcommand{{\\Fail{k}Subj{r}Dice}}{{{100 * v:.1f}}}",
                       f"\\newcommand{{\\Fail{k}Subj{r}Clean}}{{{100 * clean[p]:.1f}}}",
                       f"\\newcommand{{\\Fail{k}Subj{r}CleanRank}}{{{list(clean.index).index(p) + 1}}}"]
        if name in ("unet_dacmnorm", "swinunetr_dacmnorm"):
            rng = np.random.default_rng(0)
            pts = st.assign(x=st.type.map({t_: i for i, t_ in enumerate(TYPES)}) + rng.uniform(-0.25, 0.25, len(st)),
                            y=100 * st.dice, hcm=(st.group == "HCM").astype(int))
            pts[["x", "y", "hcm", "type", "group"]].to_csv(out / f"fail_points_{name.split('_')[0]}.csv",
                                                           index=False, float_format="%.3f")
    pertype(root, out, macros)
    (out / "numbers_structures.tex").write_text("\n".join(macros) + "\n")
    print(Path(out / "table_structures.tex").read_text())


if __name__ == "__main__":
    main()
