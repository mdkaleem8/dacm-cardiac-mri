"""Slice-position analysis (E3): Dice for basal, mid and apical slices.

Slices that contain the heart in the reference ED segmentation are split into
thirds from base (first slice in ACDC ordering) to apex. Per-slice Dice is
averaged over structures present in the reference. Uses the estimated
conditioning for DACM runs. Writes slices.csv per run and
table_slices.tex for the paper.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from dacm import degradations as deg  # noqa: E402
from dacm.data import load_subject, zscore  # noqa: E402
from dacm.metrics import CLASSES, dice  # noqa: E402
from dacm.models import DegradationEstimator  # noqa: E402
from evaluate import load_run, predict  # noqa: E402

VERS = [("default", "Default"), ("aug", "Augmentation-only"), ("dacm", "DACM (stage)"), ("dacmnorm", "DACM (norm)")]
BACKS = [("unet", "U-Net"), ("swinunetr", "Swin-UNETR")]


def position(gt_ed):
    idx = np.flatnonzero(gt_ed.reshape(gt_ed.shape[0], -1).any(1))
    pos = {}
    if len(idx) == 0:
        return pos
    thirds = np.array_split(idx, 3)
    for name, part in zip(("Basal", "Mid", "Apical"), thirds):
        for z in part:
            pos[int(z)] = name
    return pos


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", required=True)
    ap.add_argument("--testset", required=True)
    ap.add_argument("--estimator", required=True)
    ap.add_argument("--runs_root", required=True)
    ap.add_argument("--paper_results", required=True)
    ap.add_argument("--level", default="1.0")
    ap.add_argument("--suffix", default="", help="run-name suffix of the seed, e.g. _s1")
    a = ap.parse_args()
    dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    ts = Path(a.testset)
    pids = json.loads((ts / "conditions.json").read_text())["pids"]
    est = DegradationEstimator(deg.K).to(dev).eval()
    est.load_state_dict(torch.load(Path(a.estimator) / "estimator.pt", map_location=dev))
    conds = ["clean_0.0"] + [f"{k}_{a.level}" for k in deg.TYPES]
    subs = {p: load_subject(Path(a.cache), p) for p in pids}
    results = {}
    for b, _ in BACKS:
        for v, _ in VERS:
            run = Path(a.runs_root) / f"{b}_{v}{a.suffix}"
            if not (run / "model.pt").exists() or not (run / "done.json").exists():
                continue
            out_csv = run / "slices.csv"
            if out_csv.exists():
                results[(b, v)] = pd.read_csv(out_csv)
                continue
            model, args = load_run(run, dev)
            rows = []
            for cond in conds:
                data = np.load(ts / f"{cond}.npz")
                for pid in pids:
                    pos = position(subs[pid]["gt_ED"])
                    for ph in ("ED", "ES"):
                        x = np.stack([zscore(s.astype(np.float32)) for s in data[f"{pid}_{ph}_x"]])[:, None]
                        z = torch.cat([est.conditioning(torch.from_numpy(x[i:i + 64]).to(dev)).float()
                                       for i in range(0, len(x), 64)])
                        pred = predict(model, args, x, z, dev)
                        gt = subs[pid][f"gt_{ph}"]
                        for zi, name in pos.items():
                            ds = [dice(pred[zi] == c, gt[zi] == c) for c in CLASSES if (gt[zi] == c).any()]
                            if ds:
                                rows.append({"cond": cond, "pid": pid, "phase": ph, "pos": name,
                                             "dice": float(np.mean(ds))})
                print(b, v, cond, flush=True)
            df = pd.DataFrame(rows)
            df.to_csv(out_csv, index=False)
            results[(b, v)] = df
    if not results:
        return
    macros = ["% generated by eval_slices.py"]
    lines = [r"\begin{tabular}{@{}llcccccc@{}}", r"\toprule",
             r" & & \multicolumn{3}{c}{Clean} & \multicolumn{3}{c}{$s{=}" + a.level + r"$} \\",
             r"\cmidrule(lr){3-5}\cmidrule(l){6-8}",
             r"Backbone & Version & Basal & Mid & Apical & Basal & Mid & Apical \\", r"\midrule"]
    for b, bl in BACKS:
        present = [(v, vl) for v, vl in VERS if (b, v) in results]
        for j, (v, vl) in enumerate(present):
            d = results[(b, v)]
            sub_mean = d.groupby(["cond", "pid", "pos"]).dice.mean().reset_index()
            cells = []
            for clean in (True, False):
                dd = sub_mean[(sub_mean.cond == "clean_0.0") == clean]
                for p in ("Basal", "Mid", "Apical"):
                    val = f"{100 * dd[dd.pos == p].dice.mean():.1f}"
                    cells.append(val)
                    key = b.replace("swinunetr", "swin")
                    macros.append(f"\\newcommand{{\\Slice{key}{v}{'Clean' if clean else 'Ten'}{p}}}{{{val}}}")
            lines.append(f"{bl if j == 0 else ''} & {vl} & " + " & ".join(cells) + r" \\")
        if present and b != BACKS[-1][0]:
            lines.append(r"\midrule")
    if lines[-1] == r"\midrule":
        lines.pop()
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(a.paper_results).mkdir(parents=True, exist_ok=True)
    (Path(a.paper_results) / "table_slices.tex").write_text("\n".join(lines))
    (Path(a.paper_results) / "numbers_slices.tex").write_text("\n".join(macros) + "\n")


if __name__ == "__main__":
    main()
